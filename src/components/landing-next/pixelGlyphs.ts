export type PixelGlyph = keyof typeof PIXEL_GLYPHS

/** The lit cells of a glyph as [column, row] pairs. */
export function litCells(glyph: PixelGlyph): [number, number][] {
  const cells: [number, number][] = []
  PIXEL_GLYPHS[glyph].forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') cells.push([x, y])
    }
  })
  return cells
}
